function isSupportedImageUri(uri?: string): boolean {
  if (!uri || typeof uri !== 'string') return false;
  const trimmed = uri.trim();
  return (
    trimmed.startsWith('http://') ||
    trimmed.startsWith('https://') ||
    trimmed.startsWith('file://') ||
    trimmed.startsWith('content://') ||
    trimmed.startsWith('ph://') ||
    trimmed.startsWith('asset://') ||
    trimmed.startsWith('data:image/')
  );
}

export function isGenericFallbackImageUrl(uri?: string): boolean {
  if (!uri || typeof uri !== 'string') return true;
  return GENERIC_FALLBACK_URLS.has(uri.trim());
}

function singularizeWord(word: string): string {
  if (word.length <= 3) return word;
  if (word.endsWith('ies') && word.length > 4) {
    return `${word.slice(0, -3)}y`;
  }
  if (word.endsWith('oes') && word.length > 4) {
    return word.slice(0, -2);
  }
  if (word.endsWith('ses') || word.endsWith('ches') || word.endsWith('shes')) {
    return word.slice(0, -2);
  }
  if (word.endsWith('s') && !word.endsWith('ss')) {
    return word.slice(0, -1);
  }
  return word;
}

function escapeRegExp(str: string): string {
  return str.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function normalizeCommodityText(raw: string): string {
  return raw
    .toLowerCase()
    .replace(/[()[\]{},._\-/\\+|&]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Resolves a commodity name (English, plural, regional transliteration, or Devanagari/Kannada)
 * to a canonical key in DEFAULT_PRODUCT_IMAGES, or null if unrecognized.
 */
export function resolveCommodityKey(name?: string): string | null {
  if (!name || typeof name !== 'string') return null;

  const rawTrimmed = name.trim().toLowerCase();
  if (!rawTrimmed) return null;

  const cleanName = normalizeCommodityText(rawTrimmed);
  if (!cleanName) return null;

  // 1. Direct exact match in aliases or canonical dictionary
  if (COMMODITY_ALIASES[cleanName] && DEFAULT_PRODUCT_IMAGES[COMMODITY_ALIASES[cleanName]]) {
    return COMMODITY_ALIASES[cleanName];
  }
  if (DEFAULT_PRODUCT_IMAGES[cleanName]) {
    return cleanName;
  }

  // 2. Direct singularized whole-string match (e.g. "Tomatoes" -> "tomato")
  const singularWhole = singularizeWord(cleanName);
  if (COMMODITY_ALIASES[singularWhole] && DEFAULT_PRODUCT_IMAGES[COMMODITY_ALIASES[singularWhole]]) {
    return COMMODITY_ALIASES[singularWhole];
  }
  if (DEFAULT_PRODUCT_IMAGES[singularWhole]) {
    return singularWhole;
  }

  // 3. Multi-word phrases & token boundary matching (longest phrase first)
  const sortedAliases = Object.keys(COMMODITY_ALIASES).sort((a, b) => b.length - a.length);
  for (const alias of sortedAliases) {
    const regex = new RegExp(`(^|\\s)${escapeRegExp(alias)}(\\s|$)`, 'i');
    if (regex.test(cleanName)) {
      const canonical = COMMODITY_ALIASES[alias];
      if (DEFAULT_PRODUCT_IMAGES[canonical]) {
        return canonical;
      }
    }
  }

  // 4. Token-by-token matching (exact, singularized, and alias check)
  const words = cleanName.split(' ');
  for (const word of words) {
    if (word.length < 2) continue;
    const candidates = [word, singularizeWord(word)];
    for (const cand of candidates) {
      if (COMMODITY_ALIASES[cand] && DEFAULT_PRODUCT_IMAGES[COMMODITY_ALIASES[cand]]) {
        return COMMODITY_ALIASES[cand];
      }
      if (DEFAULT_PRODUCT_IMAGES[cand]) {
        return cand;
      }
    }
  }

  // 5. Compound / concatenated word fallback (e.g. "greenchilli", "redtomato", "alphonsomango")
  const compact = cleanName.replace(/\s+/g, '');
  if (compact.length >= 4) {
    for (const alias of sortedAliases) {
      if (alias.length >= 4 && !alias.includes(' ') && compact.includes(alias)) {
        const canonical = COMMODITY_ALIASES[alias];
        if (DEFAULT_PRODUCT_IMAGES[canonical]) {
          return canonical;
        }
      }
    }
    for (const key of Object.keys(DEFAULT_PRODUCT_IMAGES)) {
      if (key.length >= 4 && compact.includes(key)) {
        return key;
      }
    }
  }

  return null;
}

export function getProductEmoji(name?: string, category?: string): string {
  const resolved = resolveCommodityKey(name);
  if (resolved && CANONICAL_EMOJIS[resolved]) {
    return CANONICAL_EMOJIS[resolved];
  }

  if (category) {
    const c = category.toLowerCase().trim();
    if (CATEGORY_EMOJIS[c]) return CATEGORY_EMOJIS[c];
  }

  return '📦';
}

/**
 * Finds the best-matching commodity image based on explicit custom image, product name, or category.
 * Ignores previously-saved generic placeholder URLs when the product name matches a known commodity.
 */
export function getProductImage(product?: {
  name?: string;
  category?: string;
  image?: string;
}): string {
  if (!product) return CLEAN_PRODUCT_PLACEHOLDER;

  const explicitUri = typeof product.image === 'string' ? product.image.trim() : '';

  // 1. If user explicitly set a non-placeholder image URL or local file URI, use it
  if (isSupportedImageUri(explicitUri) && !isGenericFallbackImageUrl(explicitUri)) {
    return explicitUri;
  }

  // 2. Match commodity by name (handles plurals, varieties, regional names, Hindi/Kannada scripts)
  const resolvedKey = resolveCommodityKey(product.name);
  if (resolvedKey && DEFAULT_PRODUCT_IMAGES[resolvedKey]) {
    return DEFAULT_PRODUCT_IMAGES[resolvedKey];
  }

  // 3. Preserve explicit placeholder/category URI if given, else resolve category fallback
  if (isSupportedImageUri(explicitUri)) {
    return explicitUri;
  }

  return getCategoryFallback(product.category);
}

function getCategoryFallback(category?: string): string {
  if (!category) return CLEAN_PRODUCT_PLACEHOLDER;
  const catKey = category.toLowerCase().trim();
  if (DEFAULT_CATEGORY_IMAGES[catKey]) {
    return DEFAULT_CATEGORY_IMAGES[catKey];
  }
  for (const [k, url] of Object.entries(DEFAULT_CATEGORY_IMAGES)) {
    if (catKey.includes(k) && url !== CLEAN_PRODUCT_PLACEHOLDER) {
      return url;
    }
  }
  return CLEAN_PRODUCT_PLACEHOLDER;
}

export function getCategoryImage(categoryName?: string): string {
  if (!categoryName) return DEFAULT_CATEGORY_IMAGES.default;
  const key = categoryName.toLowerCase().trim();
  if (DEFAULT_CATEGORY_IMAGES[key]) {
    return DEFAULT_CATEGORY_IMAGES[key];
  }
  for (const [k, url] of Object.entries(DEFAULT_CATEGORY_IMAGES)) {
    if (key.includes(k)) {
      return url;
    }
  }
  return DEFAULT_CATEGORY_IMAGES.default;
}

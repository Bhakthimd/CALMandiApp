/**
 * Finds the best-matching commodity image based on product name, category, or custom image.
 * Uses exact matching, alias translation, and token boundary analysis to avoid incorrect image reuse.
 */
export function getProductImage(product?: {
  name?: string;
  category?: string;
  image?: string;
}): string {
  if (!product) return CLEAN_PRODUCT_PLACEHOLDER;

  // 1. Explicit valid image URL assigned by user
  if (product.image && typeof product.image === 'string' && product.image.trim().startsWith('http')) {
    return product.image.trim();
  }

  const rawName = (product.name || '').trim().toLowerCase();
  if (!rawName) {
    return getCategoryFallback(product.category);
  }

  // Clean string to letters, numbers, and single spaces
  const cleanName = rawName.replace(/[^a-z0-9\s]/g, ' ').replace(/\s+/g, ' ').trim();

  // 2. Direct match in commodity aliases or canonical dictionary
  if (COMMODITY_ALIASES[cleanName]) {
    const canonicalKey = COMMODITY_ALIASES[cleanName];
    if (DEFAULT_PRODUCT_IMAGES[canonicalKey]) {
      return DEFAULT_PRODUCT_IMAGES[canonicalKey];
    }
  }

  if (DEFAULT_PRODUCT_IMAGES[cleanName]) {
    return DEFAULT_PRODUCT_IMAGES[cleanName];
  }

  // 3. Multi-word phrases & token boundary matching (sort keys by length descending to match longest phrase first)
  const sortedAliases = Object.keys(COMMODITY_ALIASES).sort((a, b) => b.length - a.length);
  for (const alias of sortedAliases) {
    // Check if alias exists as a full word/phrase in cleanName
    const regex = new RegExp(`(^|\\s)${alias.replace(/[.*+?^${}()|[\\]\\]/g, '\\$&')}(\\s|$)`, 'i');
    if (regex.test(cleanName)) {
      const canonical = COMMODITY_ALIASES[alias];
      if (DEFAULT_PRODUCT_IMAGES[canonical]) {
        return DEFAULT_PRODUCT_IMAGES[canonical];
      }
    }
  }

  // 4. Token-by-token matching against default product image keys
  const words = cleanName.split(' ');
  for (const word of words) {
    if (word.length >= 3 && DEFAULT_PRODUCT_IMAGES[word]) {
      return DEFAULT_PRODUCT_IMAGES[word];
    }
  }

  // 5. Category fallback
  return getCategoryFallback(product.category);
}

function getCategoryFallback(category?: string): string {
  if (!category) return CLEAN_PRODUCT_PLACEHOLDER;
  const catKey = category.toLowerCase().trim();
  if (DEFAULT_CATEGORY_IMAGES[catKey]) {
    return DEFAULT_CATEGORY_IMAGES[catKey];
  }
  for (const [k, url] of Object.entries(DEFAULT_CATEGORY_IMAGES)) {
    if (catKey.includes(k) && url !== CLEAN_PRODUCT_PLACEHOLDER) {
      return url;
    }
  }
  return CLEAN_PRODUCT_PLACEHOLDER;
}

export function getCategoryImage(categoryName?: string): string {
  if (!categoryName) return DEFAULT_CATEGORY_IMAGES.default;
  const key = categoryName.toLowerCase().trim();
  if (DEFAULT_CATEGORY_IMAGES[key]) {
    return DEFAULT_CATEGORY_IMAGES[key];
  }
  for (const [k, url] of Object.entries(DEFAULT_CATEGORY_IMAGES)) {
    if (key.includes(k)) {
      return url;
    }
  }
  return DEFAULT_CATEGORY_IMAGES.default;
}

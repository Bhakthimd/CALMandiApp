import React, { useMemo } from 'react';
import {
  View,
  Text,
  StyleSheet,
  ScrollView,
  TouchableOpacity,
  Image,
  Share,
  Linking,
} from 'react-native';
import { useSafeAreaInsets } from 'react-native-safe-area-context';
import { Ionicons } from '@expo/vector-icons';
import { useTheme } from '../context/ThemeContext';
import { useLanguage } from '../context/LanguageContext';
import { ThemeColors } from '../styles/theme';
import { getProductImage } from '../utils/productImages';

export default function TransactionConfirmationScreen({ route, navigation }: any) {
  const insets = useSafeAreaInsets();
  const { colors, isDark } = useTheme();
  const { t } = useLanguage();
  const styles = useMemo(() => getStyles(colors, isDark), [colors, isDark]);

  const {
    transactionNumber = 'TXN-001',
    transactionType = 'SALE',
    partyName = 'Customer',
    partyType = 'Buyer',
    items = [],
    totalBill = 0,
    amountPaid = 0,
    remainingBalance = 0,
    receiptId,
  } = route?.params || {};

  const isSale = transactionType === 'SALE' || transactionType === 'INVOICE';

  const handleShare = async () => {
    const itemLines = items
      .map(
        (it: any) =>
          `• ${it.name}: ${it.quantity} ${it.unit}${it.rate ? ` @ ₹${it.rate}` : ''}${it.amount ? ` = ₹${it.amount}` : ''}`
      )
      .join('\n');

    const msg =
      `*CAL Mandi - Transaction Receipt*\n` +
      `--------------------------------\n` +
      `*Txn No:* ${transactionNumber}\n` +
      `*${isSale ? 'Buyer' : 'Farmer'}:* ${partyName} (${partyType})\n` +
      `*Type:* ${isSale ? 'Outward Dispatch (Sale)' : 'Inward Arrival'}\n` +
      `--------------------------------\n` +
      `*Items:*\n${itemLines}\n` +
      `--------------------------------\n` +
      `*Total Bill:* ₹${totalBill.toLocaleString('en-IN')}\n` +
      `*Amount Paid:* ₹${amountPaid.toLocaleString('en-IN')}\n` +
      `*Remaining Balance:* ₹${remainingBalance.toLocaleString('en-IN')}\n` +
      `--------------------------------\n` +
      `Generated by CAL Mandi Ops`;

    try {
      const whatsappUrl = `whatsapp://send?text=${encodeURIComponent(msg)}`;
      const canOpen = await Linking.canOpenURL(whatsappUrl);
      if (canOpen) {
        await Linking.openURL(whatsappUrl);
      } else {
        await Share.share({ message: msg });
      }
    } catch {
      Share.share({ message: msg });
    }
  };

  const handleViewBill = () => {
    if (isSale) {
      navigation.navigate('PattiReceipt', {
        invoiceId: receiptId || transactionNumber,
        type: 'INVOICE',
      });
    } else {
      navigation.navigate('PattiReceipt', {
        pattiId: receiptId || transactionNumber,
        type: 'PATTI',
      });
    }
  };

  const handleBackToDashboard = () => {
    navigation.replace('Home');
  };

  return (
    <View style={styles.container}>
      <ScrollView
        contentContainerStyle={[
          styles.content,
          {
            paddingTop: Math.max(insets.top + 20, 48),
            paddingBottom: Math.max(insets.bottom + 24, 36),
          },
        ]}
        showsVerticalScrollIndicator={false}
      >
        {/* Success Icon & Header */}
        <View style={styles.successHeader}>
          <View style={styles.successIconCircle}>
            <Ionicons name="checkmark" size={44} color="#FFFFFF" />
          </View>
          <Text style={styles.successTitle}>
            {isSale ? 'Sale Recorded Successfully' : 'Inward Arrival Saved'}
          </Text>
          <Text style={styles.successSub}>
            Stock inventory and customer khata have been updated.
          </Text>
        </View>

        {/* Transaction Summary Card */}
        <View style={styles.card}>
          {/* Header Row: Txn Number & Date */}
          <View style={styles.cardHeaderRow}>
            <View>
              <Text style={styles.txnLabel}>TRANSACTION NUMBER</Text>
              <Text style={styles.txnNumber}>#{transactionNumber}</Text>
            </View>
            <View style={styles.typeBadge}>
              <Text style={styles.typeBadgeText}>
                {isSale ? 'OUTWARD SALE' : 'INWARD ARRIVAL'}
              </Text>
            </View>
          </View>

          {/* Customer / Party Row */}
          <View style={styles.partyRow}>
            <View style={styles.partyAvatar}>
              <Ionicons
                name={isSale ? 'cart-outline' : 'leaf-outline'}
                size={20}
                color="#16834A"
              />
            </View>
            <View style={{ flex: 1, marginLeft: 10 }}>
              <Text style={styles.partyLabel}>{isSale ? 'Customer / Buyer' : 'Farmer / Supplier'}</Text>
              <Text style={styles.partyName}>{partyName}</Text>
            </View>
          </View>

          <View style={styles.divider} />

          {/* Selected Products List */}
          <Text style={styles.sectionTitle}>ITEMS IN TRANSACTION</Text>
          {items.map((item: any, idx: number) => (
            <View key={`item_${idx}`} style={styles.itemRow}>
              <Image
                source={{ uri: getProductImage({ name: item.name }) }}
                style={styles.itemThumb}
              />
              <View style={styles.itemInfo}>
                <Text style={styles.itemName}>{item.name}</Text>
                <Text style={styles.itemMeta}>
                  {item.quantity} {item.unit} {item.rate ? `@ ₹${item.rate}/${item.unit}` : ''}
                </Text>
              </View>
              {item.amount !== undefined && (
                <Text style={styles.itemAmount}>
                  ₹{item.amount.toLocaleString('en-IN')}
                </Text>
              )}
            </View>
          ))}

          <View style={styles.divider} />

          {/* Financial Breakdown */}
          <View style={styles.financeRow}>
            <Text style={styles.financeLabel}>Total Bill Amount</Text>
            <Text style={styles.financeTotal}>₹{totalBill.toLocaleString('en-IN')}</Text>
          </View>

          <View style={styles.financeRow}>
            <Text style={styles.financeLabel}>Amount Paid</Text>
            <Text style={styles.financePaid}>₹{amountPaid.toLocaleString('en-IN')}</Text>
          </View>

          <View style={[styles.financeRow, styles.balanceHighlightRow]}>
            <Text style={styles.balanceHighlightLabel}>Remaining Balance</Text>
            <Text
              style={[
                styles.balanceHighlightValue,
                remainingBalance > 0
                  ? { color: '#DC2626' }
                  : { color: isDark ? '#4ADE80' : '#16834A' },
              ]}
            >
              ₹{remainingBalance.toLocaleString('en-IN')}
            </Text>
          </View>
        </View>

        {/* Action Buttons: View Bill, Share Bill, Back to Dashboard */}
        <View style={styles.actionsWrap}>
          {/* Share Bill Button */}
          <TouchableOpacity
            style={styles.shareButton}
            activeOpacity={0.8}
            onPress={handleShare}
          >
            <Ionicons name="logo-whatsapp" size={20} color="#FFFFFF" />
            <Text style={styles.shareButtonText}>{t('shareBill', 'Share Bill on WhatsApp')}</Text>
          </TouchableOpacity>

          {/* View Bill Button */}
          <TouchableOpacity
            style={styles.viewBillButton}
            activeOpacity={0.8}
            onPress={handleViewBill}
          >
            <Ionicons name="document-text-outline" size={20} color={isDark ? '#4ADE80' : '#16834A'} />
            <Text style={styles.viewBillButtonText}>{t('viewBill', 'View Full Bill & Print')}</Text>
          </TouchableOpacity>

          {/* Back to Dashboard Button */}
          <TouchableOpacity
            style={styles.dashboardButton}
            activeOpacity={0.8}
            onPress={handleBackToDashboard}
          >
            <Ionicons name="home-outline" size={18} color={colors.textSecondary} />
            <Text style={styles.dashboardButtonText}>{t('backToDashboard', 'Back to Dashboard')}</Text>
          </TouchableOpacity>
        </View>
      </ScrollView>
    </View>
  );
}

